fs::path game_config_dir(const fs::path& home, const std::string& game_id) {
    return home / "config" / "games" / fs::u8path(game_id);
}

bool write_text(const fs::path& file, const std::string& text, std::string& error) {
    std::error_code ec;
    fs::create_directories(file.parent_path(), ec);
    std::ofstream out(file, std::ios::binary | std::ios::trunc);
    out << text;
    if (!out) {
        error = "No se pudo escribir " + file.u8string();
        return false;
    }
    return true;
}

std::string json_string(const std::string& text) {
    std::string out = "\"";
    for (const char c : text) {
        if (c == '"' || c == '\\') out += '\\';
        if (static_cast<unsigned char>(c) < 0x20) continue;
        out += c;
    }
    return out + '"';
}

// file:// URL of a local path, percent-encoding what a URL cannot hold (spaces, &, #, non-ASCII...).
std::string file_url(const fs::path& path) {
    std::string p = path.generic_u8string();
    std::string out = "file://";
    if (!p.empty() && p[0] != '/') out += '/';  // Windows drive letter
    static const char* kHex = "0123456789ABCDEF";
    for (const unsigned char c : p) {
        if (std::isalnum(c) || c == '/' || c == '-' || c == '_' || c == '.' || c == '~' || c == ':') out += static_cast<char>(c);
        else { out += '%'; out += kHex[c >> 4]; out += kHex[c & 15]; }
    }
    return out;
}

// Runs in every page of the wrapper app before the game's own scripts (package.json "inject_js_start").
constexpr const char* kBrowserScript = R"JS(// RPG2LX browser engine: runs in NW.js before the game's scripts. Generated by rpg2lx; edits are overwritten.
(function () {
    if (!/\/index\.html$/i.test(location.pathname)) return;  // the wrapper's start page
    var env = (typeof process !== 'undefined' && process.env) || {};
    var fs = typeof require === 'function' ? require('fs') : null;
    function log(message) {
        if (fs && env.RPG2LX_BROWSER_LOG) try { fs.appendFileSync(env.RPG2LX_BROWSER_LOG, '[browser] ' + message + '\n'); } catch (e) {}
    }
    log('start ' + location.href + ' | NW.js ' + (process.versions && process.versions.nw) + ' | Chromium ' + (process.versions && process.versions.chromium));
    window.addEventListener('error', function (e) { log('ERROR ' + e.message + ' (' + String(e.filename).split('/').pop() + ':' + e.lineno + ')'); });
    // The game is the only window on the handheld. Some plugins pause while the page lacks focus, and a compositor
    // that never hands it focus would leave the game frozen, so the page always has it (as in the native engine).
    document.hasFocus = function () { return true; };
    // Buttons reach the game as keys through gptokeyb, following the HUB's control profile. MV would also read
    // the pad itself through the Gamepad API, and every button would act twice, so the page sees no pads.
    if (navigator.getGamepads) navigator.getGamepads = function () { return []; };
    window.addEventListener('unhandledrejection', function (e) { log('ERROR (promise) ' + (e.reason && (e.reason.stack || e.reason))); });

    // Plugins load modules relative to the game folder ("./js/libs/x"), but Node resolves them from the wrapper
    // app; Steam's greenworks needs a native library that is not here. Both are fixed in require itself.
    if (typeof require === 'function') {
        var gameDir = decodeURIComponent(location.pathname.replace(/\/[^\/]*$/, '')).replace(/^\/([A-Za-z]:)/, '$1');
        var realRequire = require;
        var noSteam = { initAPI: function () { return false; }, init: function () { return false; },
            isSteamRunning: function () { return false; }, getCurrentGameLanguage: function () { return 'english'; },
            getCurrentUILanguage: function () { return 'english'; }, getNumberOfAchievements: function () { return 0; },
            getAchievementNames: function () { return []; }, isCloudEnabled: function () { return false; },
            isCloudEnabledForUser: function () { return false; }, isGameOverlayEnabled: function () { return false; },
            getSteamId: function () { return { screenName: 'Player', steamId: '0', isValid: function () { return false; } }; },
            on: function () {}, once: function () {}, removeAllListeners: function () {} };
        if (typeof Proxy === 'function') noSteam = new Proxy(noSteam, { get: function (t, k) {
            if (k in t) return t[k];
            return function () { for (var i = arguments.length - 1; i >= 0; i--) if (typeof arguments[i] === 'function') {
                var cb = arguments[i]; setTimeout(function () { cb(new Error('Steam is not available')); }, 0); break; } return false; };
        } });
        window.require = function (name) {
            name = String(name);
            if (/greenworks(\.js)?$/i.test(name)) {
                try { return realRequire(gameDir + '/' + name.replace(/^\.\//, '')); } catch (e) { return noSteam; }
            }
            if (/^\.\.?\//.test(name)) {
                try { return realRequire(gameDir + '/' + name.replace(/^\.\//, '')); } catch (e) {}
            }
            return realRequire(name);
        };
        for (var k in realRequire) window.require[k] = realRequire[k];
    }

    window.addEventListener('DOMContentLoaded', function () {
        // Saves go to RPG2LX's folder for the game, shared with the native engine.
        if (window.StorageManager && env.RPG2LX_SAVE_DIR) {
            var saveDir = env.RPG2LX_SAVE_DIR.replace(/\\/g, '/').replace(/\/?$/, '/');
            StorageManager.localFileDirectoryPath = function () { return saveDir; };
            StorageManager.isLocalMode = function () { return true; };
        }
        if (window.SceneManager) {
            var catchException = SceneManager.catchException;
            SceneManager.catchException = function (e) { log('ERROR ' + (e && (e.stack || e.message))); return catchException.apply(this, arguments); };
            var onError = SceneManager.onError;
            if (onError) SceneManager.onError = function (e) { log('ERROR loading ' + (e && e.target && e.target.src)); return onError.apply(this, arguments); };
            // Closing the game (title "Exit", plugins) ends the process, back to the HUB.
            SceneManager.terminate = function () { try { nw.App.quit(); } catch (e) { window.close(); } };
        }
    });

    // Memory on Linux (the handheld has 1 GB, shared with the GPU): what NW.js's processes hold (private and
    // shared memory, RssAnon + RssShmem), what the system still has, and swap. Read asynchronously, so the game's
    // thread never waits for /proc; each perf line shows the previous reading.
    var memory = '';
    function readMemory() {
        if (!fs || process.platform !== 'linux') return;
        var exe = process.execPath, info = {}, nwKb = 0, pending = 2;  // meminfo + the /proc listing
        function done() {
            if (--pending) return;
            memory = ', nw ' + Math.round(nwKb / 1024) + ' MB, free ' + Math.round((info.MemAvailable || 0) / 1024) +
                ' MB, swap ' + Math.round(((info.SwapTotal || 0) - (info.SwapFree || 0)) / 1024) + ' MB';
        }
        fs.readFile('/proc/meminfo', 'utf8', function (err, text) {
            if (!err) text.replace(/^(\w+):\s+(\d+)/gm, function (all, key, kb) { info[key] = +kb; });
            done();
        });
        fs.readdir('/proc', function (err, names) {
            (names || []).forEach(function (pid) {
                if (!/^\d+$/.test(pid)) return;
                pending++;
                fs.readFile('/proc/' + pid + '/cmdline', 'utf8', function (err, cmd) {
                    if (err || cmd.indexOf(exe) !== 0) return done();
                    fs.readFile('/proc/' + pid + '/status', 'utf8', function (err, status) {
                        if (!err) status.replace(/^Rss(Anon|Shmem):\s+(\d+)/gm, function (all, kind, kb) { nwKb += +kb; });
                        done();
                    });
                });
            });
            done();
        });
    }
    readMemory();

    // One line every 10 s, like the native engine's "perf:" lines.
    var frames = 0, worst = 0, last = performance.now(), prev = last;
    (function tick() {
        var now = performance.now();
        frames++;
        worst = Math.max(worst, now - prev);
        prev = now;
        if (now - last >= 10000) {
            var scene = window.SceneManager && SceneManager._scene;
            log('perf: ' + (frames * 1000 / (now - last)).toFixed(1) + ' fps, worst ' + worst.toFixed(0) + ' ms, scene ' +
                (scene && scene.constructor.name) + ', js heap ' + Math.round(((performance.memory || {}).usedJSHeapSize || 0) / 1048576) + ' MB' + memory);
            readMemory();
            frames = 0; worst = 0; last = now;
        }
        requestAnimationFrame(tick);
    })();

    // Self-test (RPG2LX_BROWSER_AUTOPILOT=1): new game, 20 s on the map, save to slot 1, quit.
    if (env.RPG2LX_BROWSER_AUTOPILOT === '1') {
        var mapSince = 0;
        setInterval(function () {
            var s = window.SceneManager && SceneManager._scene;
            if (!s || !SceneManager.isCurrentSceneStarted()) return;
            if (s instanceof Scene_Title) {
                log('autopilot: new game');
                DataManager.setupNewGame();
                SceneManager.goto(Scene_Map);
            } else if (s instanceof Scene_Map) {
                if (!mapSince) { mapSince = Date.now(); log('autopilot: on map ' + $gameMap.mapId()); }
                else if (Date.now() - mapSince > 20000) {
                    $gameSystem.onBeforeSave();
                    log('autopilot: save ' + (DataManager.saveGame(1) ? 'ok' : 'FAILED') + ', quitting');
                    nw.App.quit();
                }
            } else if (Date.now() % 4000 < 500) {
                // Logos and "press start" screens: pressing OK moves them on.
                Input._currentState.ok = true;
                setTimeout(function () { Input._currentState.ok = false; }, 150);
            }
        }, 500);
    }
})();
)JS";

// gptokeyb names of the pad buttons, in PadButton order.
constexpr std::array<const char*, kPadButtonCount> kGptkButtons{{
    "a", "b", "x", "y", "back", "start", "l3", "r3", "l1", "r1", "up", "down", "left", "right", "l2", "r2",
}};

// gptokeyb key name for a key_table() id, or "" when there is none.
std::string gptk_key(const KeyInfo& key) {
    static const std::map<std::string, std::string> kActions = {
        {"act:ok", "enter"}, {"act:escape", "esc"}, {"act:menu", "esc"}, {"act:shift", "leftshift"},
        {"act:pageup", "pageup"}, {"act:pagedown", "pagedown"}, {"act:up", "up"}, {"act:down", "down"},
        {"act:left", "left"}, {"act:right", "right"}, {"act:control", "leftctrl"}, {"act:tab", "tab"},
    };
    static const std::map<std::string, std::string> kRenamed = {
        {"shift", "leftshift"}, {"ctrl", "leftctrl"}, {"alt", "leftalt"},
    };
    if (const auto a = kActions.find(key.id); a != kActions.end()) return a->second;
    if (const auto r = kRenamed.find(key.id); r != kRenamed.end()) return r->second;
    return key.id;
}

